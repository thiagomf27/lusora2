# How often a worker waiting for a render slot asks again.
RENDER_SLOT_POLL_S = 5.0


@contextmanager
def render_slot(ctx: StageContext) -> Iterator[None]:
    """Hold one of RENDER_SLOTS (default 1) for the length of a render.

    Several workers can overlap everything that waits on the network, but a
    Remotion render sizes the machine: two at once double its RAM. The slot is
    a Postgres advisory lock, so it is shared by every worker on the database
    and released by the database if a worker dies."""
    slots = parallelism("RENDER_SLOTS", 1)
    waited_since = None
    while (slot := ctx.db.try_render_slot(slots)) is None:
        if waited_since is None:
            waited_since = time.monotonic()
            # said once, so the UI shows why a video sits at 'render'
            ctx.db.event(ctx.video_id, "render", "progress",
                         f"waiting for a render slot (all {slots} in use)")
            ctx.log(f"waiting for a render slot (all {slots} in use)")
        time.sleep(RENDER_SLOT_POLL_S)
    if waited_since is not None:
        ctx.log(f"got render slot {slot} after {time.monotonic() - waited_since:.0f}s")
    try:
        yield
    finally:
        ctx.db.release_render_slot(slot)


def run_render(ctx: StageContext) -> None:
    renderer = str(ctx.cfg.get("renderer") or "auto")
    cli = ctx.config.engine_cli
    if not cli.exists():
        raise StageError("render", f"engine CLI not found at {cli} — set ENGINE_CLI")
    with render_slot(ctx):
        proc = subprocess.run(
            ["node", "--experimental-strip-types", str(cli),
             "render", "--video-dir", str(ctx.folder), "--renderer", renderer],
            capture_output=True, text=True, timeout=1800,
        )
    if proc.returncode != 0:
        reason = (proc.stderr or proc.stdout).strip().splitlines()
        raise StageError("render", f"engine failed: {reason[-1] if reason else 'no output'}")
    try:
        info = json.loads(proc.stdout.strip().splitlines()[-1])
        ctx.db.event(ctx.video_id, "render", "progress", f"renderer: {info.get('renderer')}")
        ctx.log(f"rendered via {info.get('renderer')} ({info.get('duration_s')}s)")
    except (json.JSONDecodeError, IndexError):
        ctx.log("rendered (engine reported no JSON summary)")


# ---------------- qa (D57) ----------------


def run_qa(ctx: StageContext) -> None:
    """Look at the finished file. A render that is black, silent or the wrong
    length has passed every structural check ever written for it."""
    final = ctx.artifact("final.mp4")
    expected = probe_duration("qa", ctx.artifact("audio.mp3")) if ctx.has("audio.mp3") else None
    if ctx.has("edit_plan.json"):
        # The PLAN is the expectation, not the narration: a cold open delays the
        # voiceover and an outro outlives it (D58), so the timeline is as long
        # as its last visual item.
        plan = ctx.read_json("edit_plan.json")
        vo = plan["tracks"]["audio"]["voiceover"]
        visual = plan["tracks"]["visual"]
        expected = max(
            float(vo.get("start_s", 0)) + float(vo["duration_s"]),
            float(visual[-1]["end_s"]) if visual else 0.0,
        )
    qa.check(ctx, final, expected)


# ---------------- finalize ----------------


def run_finalize(ctx: StageContext) -> None:
    final = ctx.artifact("final.mp4")
    duration = probe_duration("finalize", final)
    run_ffmpeg("finalize", [
        "-ss", f"{min(1.0, duration / 2):.2f}", "-i", str(final),
        "-frames:v", "1", "-q:v", "3", str(ctx.artifact("thumb.jpg")),
    ])
    ctx.artifact("metadata.txt").write_text(
        f"title: {ctx.video.get('title')}\nchannel: {ctx.channel_id}\n"
        f"duration_s: {duration:.2f}\nvideo_id: {ctx.video_id}\n",
        encoding="utf-8",
    )
    ctx.db.set_size(ctx.video_id, final.stat().st_size)

    # retention (D19): clips/ deleted after render if configured
    retention = ctx.cfg.get("retention") or {}
    if str(retention.get("clips", "on_render")) == "on_render":
        clips = ctx.folder / "clips"
        if clips.is_dir():
            for f in clips.iterdir():
                f.unlink()
            clips.rmdir()
            ctx.log("retention: clips/ removed after render")
