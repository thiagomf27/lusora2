def _planner_menu_for(ctx: StageContext) -> str:
    """The component menu the craft call should carry — empty when a later
    stage owns the overlay question (D87), so the two decisions never both pay
    for it."""
    stages = [st.get("name") for st in ((ctx.cfg.get("pipeline_doc") or {}).get("stages") or [])]
    if "select_overlays" in stages:
        return ""
    allowed = ((ctx.cfg.get("style_pack_doc") or {}).get("overlays") or {}).get("allowed_components")
    return planner_agent._catalog_menu(allowed)


def run_plan_beats(ctx: StageContext) -> None:
    llm = str(((ctx.cfg.get("planner") or {}).get("llm")) or "mock")
    script = ctx.artifact("script.txt").read_text(encoding="utf-8").strip()
    audio_duration = probe_duration("plan_beats", ctx.artifact("audio.mp3"))

    if llm != "mock":
        # D88: where cut_beats ran, the spans are already decided and the model
        # answers by index instead of retyping the narration. The presence of
        # the artifact is the switch, so a pipeline without the stage takes the
        # single-call path exactly as before.
        if ctx.has("beat_cuts.json"):
            cuts = ctx.read_json("beat_cuts.json")["cuts"]
            beats_doc = beatcraft_agent.craft_beats(
                ctx, cuts, script, audio_duration,
                menu=_planner_menu_for(ctx),
            )
            ctx.write_json("beats.json", beats_doc)
            ctx.log(
                f"beat sheet crafted by llm '{llm}' over {len(cuts)} code-cut spans "
                f"({len(beats_doc['beats'])} beats)"
            )
            return
        beats_doc = planner_agent.plan_beats(ctx, script, audio_duration)
        ctx.write_json("beats.json", beats_doc)
        ctx.log(f"beat sheet planned by llm '{llm}' ({len(beats_doc['beats'])} beats)")
        return

    beats_doc = _fallback_planner(ctx, script, audio_duration)
    violations = validate_beat_sheet(beats_doc, script, ctx.cfg, audio_duration)
    if violations:
        raise StageError(
            "plan_beats",
            "generated beat sheet failed validation: " + "; ".join(violations[:8]),
        )
    ctx.write_json("beats.json", beats_doc)
    ctx.log(f"beat sheet planned ({len(beats_doc['beats'])} beats, deterministic fallback planner)")


_STOPWORDS = set(
    "the a an and or of in on at to for with by from is are was were be this that it its as into over under".split()
)


def cut_script(
    ctx: StageContext, script: str, audio_duration: float = 0.0
) -> list["beatphases.Piece"]:
    """Where the narration is cut, and when each piece is spoken.

    ONE implementation, called by both the deterministic planner below and the
    `cut_beats` stage (D88). It was extracted rather than copied because these
    phases already read the style pack's hold floor and the real transcript
    timings, and a second copy would drift the moment either changed — which is
    the failure the extraction exists to prevent, not a tidy-up after it.

    split at punctuation -> align to the real transcript -> join anything under
    the pack's hold floor, because a 0.4s shot flashes by and reads as a
    mistake.
    """
    pacing = (ctx.cfg.get("style_pack_doc") or {}).get("pacing") or {}
    min_hold = float(pacing.get("min_hold", 0) or 0)
    max_hold = float(pacing.get("max_hold", 0) or 0)
    srt = read_srt(ctx.artifact("subtitles.srt")) if ctx.has("subtitles.srt") else []
    pieces = beatphases.script_split(script, srt, granularity=srt_granularity(ctx.cfg))
    aligned = beatphases.srt_alignment(pieces, srt, audio_duration)
    # The floor joins and the ceiling splits, so a pack whose floor is ABOVE
    # its ceiling would have them undo each other forever. That pack is
    # incoherent, and the floor wins: a beat below it flashes by and reads as a
    # mistake, while a beat above the ceiling merely sits there.
    return _under_the_ceiling(
        beatphases.beat_parts(aligned, min_hold),
        max(max_hold, min_hold) if max_hold else 0.0,
        min_hold,
    )


def _under_the_ceiling(
    parts: list["beatphases.Piece"], max_hold: float, min_hold: float = 0.0
) -> list["beatphases.Piece"]:
    """Split any span that holds longer than the pack's ceiling.

    `beat_parts` deliberately handles only the FLOOR, and its docstring gives
    the right reason: splitting a beat on time alone would either duplicate its
    text or leave one with none, and cutting a shot is a timeline concern the
    compiler already handles via `hold_ceiling_ratio`.

    But `cut_beats` is not choosing shots, it is choosing BEATS, and the beat
    sheet is judged on its count against the pacing window before the compiler
    ever runs. Without this, a script of long sentences produced 15 spans where
    the validator wanted 18-69, and the repair loop then spent three attempts
    asking a model to fix a number it does not control — the exact futility D88
    removed for verbatim coverage, reproduced for pacing.

    So the split is by WORDS, not by time: the same punctuation-aware splitter,
    re-run on the span's own text, with its time apportioned by character share
    the way `srt_alignment` apportions it. The text stays verbatim and
    contiguous, which is the property everything else rests on.

    `min_hold` is passed so the split cannot create a fragment the FLOOR would
    have refused. Without it the ceiling and the floor were enforced in
    different passes and only the first one was ever re-checked.
    """
    if not max_hold:
        return parts
    # Repeat until nothing is over the ceiling or nothing more can be split: one
    # pass leaves a sub-span still over it whenever the text divides unevenly,
    # which is most of the time.
    for _ in range(4):
        split = _split_once(parts, max_hold, min_hold)
        if len(split) == len(parts):
            return split
        parts = split
    return parts


def _breakpoints(text: str, wanted: int) -> list[str]:
    """Where this span may be cut, into roughly `wanted` pieces.

    Punctuation first, and only then word boundaries. The word fallback is what
    makes the ceiling reachable at all: a long sentence carrying no comma, colon
    or full stop — "Is it just a coincidence that salmonella is happening at the
    same time as cyclospora?" — offers the punctuation splitter nothing to cut
    on, so the old code kept it whole and a 12.7s shot went out on a pack whose
    ceiling is 8s. Better long than wrong was the right instinct for a splitter
    that could only guess; a word boundary is not a guess.
    """
    target_chars = max(8, len(text) // wanted + 1)
    # min_chars=1, deliberately. `_merge_undersized`'s floor exists to stop a
    # three-word fragment becoming a shot, and here it was UNDOING the split:
    # given "And it has. This summer Taylor Farms has been at the center of…"
    # it cut the two sentences apart and then folded the short one straight back
    # into the long one, returning the input unchanged. Nothing reported it,
    # because returning one piece is also what an unbreakable span looks like.
    # The floor is re-applied in `_apportion` below, where it can be measured
    # against TIME — which is what the pack's window is actually about.
    pieces = beatphases.script_split(text, None, min_chars=1, max_chars=target_chars)
    if len(pieces) > 1:
        return pieces
    return _word_split(text, wanted)


def _word_split(text: str, wanted: int) -> list[str]:
    """Cut `text` at whitespace into `wanted` roughly equal pieces.

    Slices the ORIGINAL string at space offsets rather than re-joining a word
    list, so every piece is an exact substring and the concatenation is the
    input unchanged. (`validate_beat_sheet` compares normalised text, so this is
    belt and braces — but the spans are also what a human reads in the editor,
    and silently reflowed narration reads as a bug.)
    """
    spaces = [i for i, ch in enumerate(text) if ch.isspace()]
    if wanted < 2 or not spaces:
        return [text]
    cuts: list[int] = []
    for n in range(1, wanted):
        ideal = len(text) * n / wanted
        at = min(spaces, key=lambda i: abs(i - ideal))
        if at not in cuts:
            cuts.append(at)
    pieces, prev = [], 0
    for at in sorted(cuts):
        piece = text[prev:at].strip()
        if piece:
            pieces.append(piece)
        prev = at
    tail = text[prev:].strip()
    if tail:
        pieces.append(tail)
    return pieces if len(pieces) > 1 else [text]


def _split_once(
    parts: list["beatphases.Piece"], max_hold: float, min_hold: float = 0.0
) -> list["beatphases.Piece"]:
    out: list[beatphases.Piece] = []
    for part in parts:
        if part.duration <= max_hold or not part.text.strip():
            out.append(part)
            continue
        wanted = math.ceil(part.duration / max_hold)
        runs = _apportion(part, _breakpoints(part.text, wanted), min_hold)
        if len(runs) < 2:
            # The floor put back exactly what the ceiling took apart. That is
            # not "this span cannot be cut" — it is "the cut fell in the wrong
            # place": punctuation offered a three-word opener and joining it
            # forward rebuilt the whole span. A word split is balanced by
            # construction, so no piece is under the floor unless the span
            # itself is, and then the floor genuinely does win.
            runs = _apportion(part, _word_split(part.text, wanted), min_hold)
        out.extend(runs)
    return out


def _apportion(
    part: "beatphases.Piece", pieces: list[str], min_hold: float
) -> list["beatphases.Piece"]:
    """Give each piece its character share of the span's time.

    Character share is how `srt_alignment` apportions time, and using the same
    rule here keeps one answer to "when is this spoken" rather than two. Any run
    that would land under the pack's floor is joined forward first — the rule
    `beat_parts` applies, applied again because splitting is what can create a
    fragment too short to be a shot.
    """
    span = part.end_s - part.start_s
    total = sum(len(p) for p in pieces) or 1

    runs: list[str] = []
    for piece in pieces:
        if runs and span * (len(runs[-1]) / total) < min_hold:
            runs[-1] = f"{runs[-1]} {piece}"
        else:
            runs.append(piece)
    if len(runs) > 1 and span * (len(runs[-1]) / total) < min_hold:
        tail = runs.pop()
        runs[-1] = f"{runs[-1]} {tail}"

    out: list[beatphases.Piece] = []
    cursor = part.start_s
    for i, text in enumerate(runs):
        end = part.end_s if i == len(runs) - 1 else cursor + span * (len(text) / total)
        out.append(beatphases.Piece(text, round(cursor, 3), round(end, 3)))
        cursor = end
    return out


def _fallback_planner(ctx: StageContext, script: str, audio_duration: float = 0.0) -> dict:
    """Deterministic no-LLM planner. The manual fallback for every AI failure
    (D2) — and the M3 default.

    Beat BOUNDARIES come from the named phases (`beatphases`): split the script
    at punctuation, align the pieces to the real transcript, then join anything
    under the style pack's hold floor. It used to cut every 1–2 sentences on an
    avg_hold guess, which ignored both the pack's hold window and the timings
    that were sitting in subtitles.srt the whole time — so a slow pack and a
    fast one produced the same beats.

    Only the boundaries changed. What a beat SHOWS is still the same keyword
    heuristic, because choosing visuals well needs the catalog's `type_name`
    vocabulary and the pack's overlay priority numbers, and neither is settled.
    """
    parts = cut_script(ctx, script, audio_duration)
    style = ctx.cfg.get("style_pack_doc") or {}

    beats = []
    for i, part in enumerate(parts, start=1):
        words = [
            w.lower().strip(".,!?…:;\"'")
            for w in part.text.split()
            if w.lower().strip(".,!?…:;\"'") not in _STOPWORDS
        ]
        subject = " ".join(words[:8]) or "establishing shot"
        visual = str(style.get("visual_language") or "").strip()
        intent = f"{subject}, wide establishing shot" + (f", {visual.rstrip('.').lower()}" if visual else "")
        beats.append(
            {
                "id": f"b{i}",
                "kind": "narration",
                "script_text": part.text,
                "visual_intent": intent[:300],
                "mood": "neutral",
                "media_preference": "any",
            }
        )
    return {"version": "1.0", "video_id": ctx.video_id, "beats": beats}


# ---------------- compile_plan ----------------


def _sentence_timings(ctx: StageContext) -> list[dict]:
    if ctx.has("tts_timings.json"):
        return ctx.read_json("tts_timings.json")["items"]
    return [
        {"text": s.text, "start_s": s.start_s, "end_s": s.end_s}
        for s in read_srt(ctx.artifact("subtitles.srt"))
    ]


def plan_compiled_and_fresh(ctx: StageContext) -> bool:
    """The plan is done only if it exists AND is not older than beats.json —
    an edited beat sheet triggers per-beat recompilation (D14)."""
    if not ctx.has("edit_plan.json"):
        return False
    if not ctx.has("beats.json"):
        return True
    return ctx.artifact("edit_plan.json").stat().st_mtime >= ctx.artifact("beats.json").stat().st_mtime


def run_compile_plan(ctx: StageContext) -> None:
    beats_doc = ctx.read_json("beats.json")
    audio_duration = probe_duration("compile_plan", ctx.artifact("audio.mp3"))

    # human-provided beats are validated here (agent-produced ones were already)
    script = ctx.artifact("script.txt").read_text(encoding="utf-8").strip() if ctx.has("script.txt") else ""
    if script:
        violations = validate_beat_sheet(beats_doc, script, ctx.cfg, audio_duration)
        if violations:
            raise StageError("compile_plan", "beats.json invalid: " + "; ".join(violations[:8]))

    # D87: overlays.json wins where the select_overlays stage produced one.
    # Absent on every pipeline that does not run that stage, and the compiler
    # then reads beat.overlay exactly as before.
    selection = ctx.read_json("overlays.json") if ctx.has("overlays.json") else None
    plan = compile_plan(
        beats_doc, _sentence_timings(ctx), ctx.cfg, audio_duration, selection
    )

    # per-beat recompile (D14): locked items and still-valid resolutions survive
    if ctx.has("edit_plan.json"):
        old_plan = ctx.read_json("edit_plan.json")
        beats_by_id = {b["id"]: b for b in beats_doc.get("beats", [])}
        merged = _merge_recompiled(old_plan, plan, beats_by_id)
        plan = merged
        ctx.log("per-beat recompile: locked items kept, unchanged beats keep their assets")

    structural = validate_plan(plan, ctx.folder, ctx.cfg, audio_duration, require_assets=False)
    if structural:
        raise StageError(
            "compile_plan",
            "compiler produced an invalid plan (bug): " + "; ".join(structural[:8]),
        )
    ctx.write_json("edit_plan.json", plan)
    ctx.log(f"plan compiled: {len(plan['tracks']['visual'])} visual items, "
            f"{len(plan['tracks']['overlays'])} overlays")


def _merge_recompiled(old_plan: dict, new_plan: dict, beats_by_id: dict) -> dict:
    """Merge rules (D14): a locked old item always wins over its recompiled
    counterpart; an unlocked item whose beat's visual_intent is unchanged
    keeps its resolved asset (no pointless re-sourcing); hand-added items
    (beat_id null) are preserved."""
    for track in ("visual", "overlays"):
        old_by_id = {i["id"]: i for i in old_plan["tracks"][track]}
        merged_items = []
        for item in new_plan["tracks"][track]:
            old = old_by_id.get(item["id"])
            if old is None:
                merged_items.append(item)
                continue
            if old.get("locked"):
                merged_items.append(old)
                continue
            # carry the resolved asset when the beat's intent didn't change.
            # The stored query is whatever the SOURCE was asked, which since
            # v1.1 is a keyword query for stock and the intent for the library
            # (D53) — so any of the beat's current queries counts as unchanged.
            beat = beats_by_id.get(str(item.get("beat_id")))
            old_query = ((old.get("asset") or {}).get("query") or "")[:200]
            intent = str((beat or {}).get("visual_intent") or "")
            wanted = {intent[:200]} if intent else set()
            wanted |= {str(q)[:200] for q in ((beat or {}).get("queries") or [])}
            if intent:
                wanted.add(sources.keywords_from_intent(intent)[:200])
            if old_query and old_query in wanted and (old.get("asset") or {}).get("path"):
                item["asset"] = old["asset"]
                item["media_type"] = old.get("media_type", item["media_type"])
                if "motion" in old:
                    item["motion"] = old["motion"]
            merged_items.append(item)
        # hand-added items survive every recompile
        for item in old_plan["tracks"][track]:
            if item.get("beat_id") is None and item["id"] not in {i["id"] for i in merged_items}:
                merged_items.append(item)
        key = "start_s"
        merged_items.sort(key=lambda i: float(i[key]))
        new_plan["tracks"][track] = merged_items

    # sfx follow the same rules (D48): they carry id/beat_id/locked precisely so
    # that a cue someone moved or silenced by hand is not quietly put back by
    # the next per-beat recompile.
    old_sfx = {i["id"]: i for i in (old_plan["tracks"]["audio"].get("sfx") or [])}
    new_sfx = new_plan["tracks"]["audio"].get("sfx") or []
    merged_sfx = [old_sfx[i["id"]] if old_sfx.get(i["id"], {}).get("locked") else i for i in new_sfx]
    merged_ids = {i["id"] for i in merged_sfx}
    merged_sfx += [
        i for i in old_sfx.values() if i.get("origin") == "manual" and i["id"] not in merged_ids
    ]
    if merged_sfx:
        merged_sfx.sort(key=lambda i: float(i["start_s"]))
        new_plan["tracks"]["audio"]["sfx"] = merged_sfx
    else:
        new_plan["tracks"]["audio"].pop("sfx", None)
    return new_plan


# ---------------- resolve_assets ----------------


def assets_resolved(ctx: StageContext) -> bool:
    if not ctx.has("edit_plan.json"):
        return False
    try:
        plan = ctx.read_json("edit_plan.json")
    except StageError:
        return False
    for item in plan["tracks"]["visual"]:
        if item.get("media_type") == "color":
            continue  # a colour fill has nothing to fetch (D55 fallback cards)
        path = str(item["asset"].get("path", ""))
        if not path or not (ctx.folder / path).exists():
            return False
    return True


def identities_in(plan: dict) -> dict[str, str]:
    """beat_id -> the real person that beat's shot is presented as being of.

    Read from the PLAN's overlays rather than from beats.json, because that is
    where the answer is on every pipeline: on faceless_v3 the selections live in
    overlays.json and are merged into beats only in the compiler's memory, so a
    beat sheet on disk carries no `overlay` at all.

    The signal is free and needs no new field: a component that attaches to a
    `name` anchor, with a name in its props, is the sheet declaring that a named
    someone belongs to this moment. That is the exact case in the reproduction —
    a NamePlate reading "Carsten Borchgrevink" over a stock photograph of an
    unrelated man. Slice 2's `depicts` is what widens this to the beats that
    show a person without naming one on screen.
    """
    out: dict[str, str] = {}
    for overlay in plan["tracks"]["overlays"]:
        entry = lusora_contracts.catalog_component(str(overlay.get("component", "")))
        if entry is None or "name" not in (entry.get("anchor_types") or []):
            continue
        person = _person_in(overlay.get("props") or {})
        if person:
            out[str(overlay.get("beat_id"))] = person
    return out


def _person_in(props: dict) -> str:
    """The name a name-bearing component is showing. `NamePlate` carries it
    directly; `PortraitPlates` carries one or two plates."""
    name = props.get("name")
    if isinstance(name, str) and name.strip():
        return name.strip()
    frames = props.get("frames")
    if isinstance(frames, list):
        for frame in frames:
            if isinstance(frame, dict):
                label = frame.get("name") or frame.get("label")
                if isinstance(label, str) and label.strip():
                    return label.strip()
            elif isinstance(frame, str) and frame.strip():
                return frame.strip()
    return ""


def run_resolve_assets(ctx: StageContext) -> None:
    plan = ctx.read_json("edit_plan.json")
    beats = {b["id"]: b for b in ctx.read_json("beats.json")["beats"]} if ctx.has("beats.json") else {}
    chain = ((ctx.cfg.get("source_policy") or {}).get("visual") or {}).get("chain") or []
    if not chain:
        raise StageError("resolve_assets", "source_policy.visual.chain is empty — nothing can be sourced")

    (ctx.folder / "clips").mkdir(exist_ok=True)
    sources.begin_run()
    # What this video has already put on screen (D54). Rebuilt from the plan,
    # so a worker killed mid-stage resumes with the ledger it had.
    ledger = sources.Ledger.from_plan(plan, ctx.folder, ctx.cfg)
    floor = degrade.source_score_floor(ctx.cfg)
    identities = identities_in(plan)

    def pending(item: dict) -> bool:
        path = str(item["asset"].get("path", ""))
        if path and (ctx.folder / path).exists():
            return False  # human-provided or already resolved
        return item.get("media_type") != "color"  # degraded to a card on an earlier pass

    def question(item: dict) -> tuple[dict, str, list[str], str | None]:
        beat = beats.get(str(item.get("beat_id"))) or {}
        query = str(beat.get("visual_intent") or ctx.video.get("title") or "establishing shot")
        # v1.1 (D53): keyword sources get these instead of the scout sentence
        queries = [str(q) for q in (beat.get("queries") or [])]
        return beat, query, queries, identities.get(str(item.get("beat_id")))

    # Throughput slice 4: FETCH in parallel, COMMIT in plan order. A fetch
    # searches and downloads against a snapshot of the ledger taken when it
    # starts and writes nothing else; the loop below places each answer in
    # order, exactly where the serial loop did. An answer an earlier item took
    # in the meantime is fetched again, serially, against the live ledger —
    # the question the serial loop would have asked at that point.
    ledger_lock = threading.Lock()

    def fetch(item: dict, live: bool = False) -> sources.Resolution | None:
        _beat, query, queries, person = question(item)
        if live:
            snapshot = ledger
        else:
            with ledger_lock:
                snapshot = ledger.copy()
        return sources.find_item(ctx, item, query, chain, queries, snapshot, identity=person)

    todo = [item for item in plan["tracks"]["visual"] if pending(item)]
    workers = min(len(todo), parallelism("ASSET_PARALLELISM", 4))
    pool = ThreadPoolExecutor(max_workers=workers) if workers > 1 else None
    futures = [pool.submit(fetch, item) for item in todo] if pool else []
    try:
        for n, item in enumerate(todo):
            found = futures[n].result() if pool else fetch(item)
            if found is not None and sources.conflicts(ctx, found, ledger):
                (ctx.folder / str(found["path"])).unlink(missing_ok=True)
                ctx.db.event(ctx.video_id, "resolve_assets", "progress",
                             f"beat {item.get('beat_id')}: {found.get('source')} {found.get('id')} "
                             "was taken by an earlier beat — asking again")
                found = fetch(item, live=True)
            _place(ctx, plan, item, found, question(item), ledger, ledger_lock, floor)
            # checkpoint after every item so a killed worker resumes without
            # re-downloading what it already has
            ctx.write_json("edit_plan.json", plan)
    except BaseException:
        for f in futures:
            f.cancel()  # not-yet-started fetches are not paid for
        raise
    finally:
        if pool:
            pool.shutdown(wait=True)

    if todo:
        ctx.db.event(ctx.video_id, "resolve_assets", "progress",
                     f"{sum(1 for v in plan['tracks']['visual'] if v['asset'].get('path'))} of "
                     f"{len(plan['tracks']['visual'])} items resolved")
    ctx.log("assets resolved for all visual items")


def _place(
    ctx: StageContext,
    plan: dict,
    item: dict,
    found: sources.Resolution | None,
    question: tuple[dict, str, list[str], str | None],
    ledger: sources.Ledger,
    ledger_lock: threading.Lock,
    floor: float,
) -> None:
    """One item's answer, placed: what the serial loop did per item, unchanged."""
    beat, query, _queries, person = question
    if found is not None:
        with ledger_lock:  # the fetches copy it; only this writes it
            sources.commit(ctx, item, found, ledger)
    elif person:
        # Both questions came back empty. A plain frame carrying their name is
        # a worse video than real footage and a better one than no video at
        # all, which is what this used to be.
        degrade.to_identity_card(ctx, plan, item, person)
        ctx.db.event(ctx.video_id, "resolve_assets", "progress",
                     f"beat {item.get('beat_id')}: nothing found for {person} or for "
                     "the scene — showing their name on the plate")
    else:
        raise StageError(
            "resolve_assets",
            f"source chain exhausted for beat {item.get('beat_id')} (item {item['id']}) — "
            f"query was: {query!r}; add sources, lower min_score, or edit the beat",
        )
    # A score below the floor is a match nobody would have chosen: place a
    # card that says what the beat is about instead of a clip that is nearly
    # unrelated (D55). Sources that return no score (stock, ai) are not judged
    # here — there is nothing to judge them by.
    score = (item.get("asset") or {}).get("score")
    if floor > 0 and score is not None and float(score) < floor:
        used = degrade.to_title_card(ctx, plan, item, beat)
        if used:
            ctx.db.event(ctx.video_id, "resolve_assets", "progress",
                         f"beat {item.get('beat_id')}: best match scored {float(score):.2f}, "
                         f"under min_score_floor {floor:g} — showing a {used} instead")
    else:
        strategy = degrade.apply_short_clip_policy(ctx, item)
        if strategy:
            ctx.db.event(ctx.video_id, "resolve_assets", "progress",
                         f"beat {item.get('beat_id')}: footage shorter than the beat — {strategy}")


# ---------------- resolve_audio (D48) ----------------


def _audio_items(plan: dict) -> list[dict]:
    audio = plan["tracks"]["audio"]
    return [*(audio.get("music") or []), *(audio.get("sfx") or [])]


def audio_resolved(ctx: StageContext) -> bool:
    if not ctx.has("edit_plan.json"):
        return False
    try:
        plan = ctx.read_json("edit_plan.json")
    except StageError:
        return False
    return all((ctx.folder / str(item["path"])).exists() for item in _audio_items(plan))


def run_resolve_audio(ctx: StageContext) -> None:
    """Copy the pack's cue and bed files into the video folder.

    The compiler already decided WHICH sounds play and when; this stage only
    binds names to bytes. Copying (rather than pointing at the pack) is what
    makes a video reproducible: re-rendering it next year uses the audio it was
    built with, even if the pack has been retuned since — the same reason
    cfg.json snapshots the theme (Core Principle 7).

    $0 and offline, so no budget gate and no price entry: the sounds are files
    in the repo, recorded as `library` provenance like any other local asset.
    """
    plan = ctx.read_json("edit_plan.json")
    items = _audio_items(plan)
    if not items:
        ctx.log("no music or sfx in this plan")
        return

    pack = ctx.cfg.get("sound_pack_doc") or {}
    pack_name = str(pack.get("name") or "")
    if not pack_name:
        raise StageError(
            "resolve_audio",
            "the plan carries audio items but cfg has no sound_pack_doc — "
            "re-enqueue so the pack manifest is snapshotted",
        )
    pack_dir = lusora_contracts.sound_pack_dir(pack_name)
    entries = {**(pack.get("cues") or {}), **(pack.get("beds") or {})}

    (ctx.folder / "audio").mkdir(exist_ok=True)
    copied = 0
    for item in items:
        dest = ctx.folder / str(item["path"])
        name = str(item.get("cue") or Path(str(item["path"])).stem)
        entry = entries.get(name)
        if entry is None:
            raise StageError(
                "resolve_audio",
                f"sound pack '{pack_name}' has no cue or bed named '{name}' — "
                "the pack changed after this video was enqueued",
            )
        source = pack_dir / str(entry["file"])
        if not source.exists():
            raise StageError(
                "resolve_audio",
                f"sound pack '{pack_name}' declares {entry['file']} for '{name}' but the file is missing",
            )
        if not dest.exists():
            shutil.copyfile(source, dest)
            copied += 1
        item["asset"] = {
            "source": "library",
            "id": name,
            "provider": f"sound-pack:{pack_name}",
            "license": str(pack.get("license") or "unknown"),
            "path": str(item["path"]),
        }
        # beat_id is NOT NULL in asset_usage; a bed spanning the whole video
        # legitimately has no single beat, so it records as the empty string
        ctx.db.asset_usage(
            ctx.video_id,
            str(item.get("beat_id") or ""),
            "library",
            name,
            str(pack.get("license") or "unknown"),
            f"sound-pack:{pack_name}",
        )

    ctx.write_json("edit_plan.json", plan)
    ctx.log(f"audio resolved from pack '{pack_name}': {len(items)} items, {copied} copied")


